import path from 'node:path';
import fs from 'node:fs/promises';
import {root,full,fixture,init,prepare,command,write,assert,receipt,complete} from './cadence-pipeline-operations.mjs';
const a=await fixture('lead-a',{delay:1800}), b=await fixture('lead-b');
const state=path.join(root,'lead-state');
await init(state,a);const prepared=await prepare(state,a);
const read=()=>fs.readFile(path.join(state,'state.json'),'utf8').then(JSON.parse);
const candidate=(await read()).candidates.at(-1);
const pending=command(full,state,'checkpoint',{id:'build',artifacts:[{path:path.join(a.repo,'dist/app.mjs')}]});
await new Promise(r=>setTimeout(r,300));
const at=Date.now();await command(full,state,'status');assert(Date.now()-at<1200,'status waited for build mutex');
const admitted=await command(full,state,'work-ahead admit',{id:'next',predecessorCandidateId:candidate.id,authorityRefs:['operator:approved-boundary'],canonicalScopeRefs:['fixture:next'],owner:'lead',ownedPaths:[b.repo],scope:b.scope,featureOperation:b.featureOperation,baseSourceRefs:b.sourceRefs,checkoutRoots:[b.repo],outputRoots:[path.join(b.repo,'dist')],checkpoints:b.checkpoints,dependencyClass:'independent'});
await command(full,state,'work-ahead start',{id:'next'});
await write(path.join(b.repo,'data.json'),{value:3});
await command(full,state,'work-ahead promote',{id:'next'},'early-promote',false);
await pending;
await command(full,state,'checkpoint',{id:'launch'});await command(full,state,'checkpoint',{id:'feature'});
await command(full,state,'finish',{completion:{tasks:a.scope.tasks,changes:a.scope.changes,phases:[]}});
const firstWork=(await read()).workAhead[0].firstWorkAt;
await command(full,state,'work-ahead promote',{id:'next'});
let s=await read();const active=s.iterations.find(i=>i.id===s.activeIterationId);assert(active.firstWorkAt===firstWork,'promotion lost original time');
await command(full,state,'ready',{codeComplete:true});await complete(state,b);
s=await read();assert(s.successfulDeliveries===2,'two deliveries not counted');assert(s.obligations.length===1,'two-delivery publication missing');
await receipt('pipeline-overlap',{status:'passed',state,firstWorkAt:firstWork,successfulDeliveries:s.successfulDeliveries,obligations:s.obligations.length,detail:'Actual builds and feature operations; status and isolated future admission while build running; early promotion refused'});
